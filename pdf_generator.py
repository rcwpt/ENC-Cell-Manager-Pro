# Two-Pass Numbered Canvas for "Page X of Y" & Running Header
# ---------------------------------------------------------
class NumberedCanvas(canvas.Canvas):
    header_title = "ENC REQUISITION REPORT"
    vessel_name = "PROSPERA"
    ref_code = ""
    footer_note = "Generated by ENC Cell Manager Pro • Official ADMIRALTY Standard AVCS Requisition • IMO SOLAS V/19 & V/27"
    theme_color = "#0f2b48"

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        page_w, page_h = A4
        margin = 24  # 24 pt = 8.5 mm

        # Running Header on page 2 and later
        if self._pageNumber > 1:
            self.setFont("Helvetica-Bold", 7.5)
            self.setFillColor(colors.HexColor(self.theme_color))
            self.drawString(margin, page_h - 18, f"{self.header_title} — VESSEL: {self.vessel_name}")
            
            if self.ref_code:
                self.setFont("Helvetica", 7.5)
                self.setFillColor(colors.HexColor("#64748b"))
                self.drawRightString(page_w - margin, page_h - 18, f"REF: {self.ref_code}")

            # Top thin rule
            self.setStrokeColor(colors.HexColor("#cbd5e1"))
            self.setLineWidth(0.6)
            self.line(margin, page_h - 22, page_w - margin, page_h - 22)

        # Footer on all pages
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.6)
        self.line(margin, 22, page_w - margin, 22)

        self.setFont("Helvetica", 7)
        self.setFillColor(colors.HexColor("#64748b"))
        self.drawString(margin, 12, self.footer_note)

        # Page numbering
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.setFont("Helvetica-Bold", 7)
        self.setFillColor(colors.HexColor(self.theme_color))
        self.drawRightString(page_w - margin, 12, page_text)

        self.restoreState()


